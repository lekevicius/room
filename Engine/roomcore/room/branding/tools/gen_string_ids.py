#!/usr/bin/env python3
"""Writes every IDS_ resource id the given grit headers define, one per line, as a C++
initializer list (//room/branding:string_ids)."""
import re
import sys

out, headers = sys.argv[1], sys.argv[2:]
ids = set()
for header in headers:
    with open(header, encoding='utf-8') as f:
        for match in re.finditer(r'^#define (IDS_\w+) (\d+)$', f.read(), re.M):
            ids.add(int(match.group(2)))
text = '// Generated by //room/branding/tools/gen_string_ids.py from %d headers.\n' % len(headers)
text += ''.join('%d,\n' % i for i in sorted(ids))
try:
    with open(out, encoding='utf-8') as f:
        if f.read() == text:
            sys.exit(0)
except FileNotFoundError:
    pass
with open(out, 'w', encoding='utf-8') as f:
    f.write(text)
