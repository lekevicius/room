#!/usr/bin/env python3
"""5.12: writes Packages/Sidebar/Sources/Sidebar/EmojiCatalog.swift, the icon picker's emoji, from
Unicode's emoji-test.txt (the Unicode data licence; a copy ships in the Chromium checkout:
$CHROMIUM_ROOT/src/third_party/rust/chromium_crates_io/vendor/unicode-width-v0_2/tests/emoji-test.txt).
Fully-qualified emoji up to MAX_VERSION (what macOS draws), without skin-tone or hair variants
(the base emoji stands for them), in Unicode's order and groups, with their CLDR names for search.
Usage: scripts/gen-emoji-catalog.py <emoji-test.txt>"""
import re, sys
MAX_VERSION = 16.0
SKIN = set(range(0x1F3FB, 0x1F400))
HAIR = set(range(0x1F9B0, 0x1F9B4))
src = sys.argv[1]
groups, current = [], None
for line in open(src, encoding="utf-8"):
    if line.startswith("# group:"):
        name = line.split(":", 1)[1].strip()
        if name == "Component":
            current = None
            continue
        current = (name, [])
        groups.append(current)
        continue
    if current is None or line.startswith("#") or not line.strip():
        continue
    m = re.match(r"^([0-9A-F ]+)\s*;\s*fully-qualified\s*#\s*(\S+)\s+E(\d+\.\d+)\s+(.*)$", line.strip())
    if not m:
        continue
    points = [int(p, 16) for p in m.group(1).split()]
    if float(m.group(3)) > MAX_VERSION or any(p in SKIN or p in HAIR for p in points):
        continue
    current[1].append((m.group(2), m.group(4).strip()))
symbols = {
    "Smileys & Emotion": "face.smiling", "People & Body": "hand.raised", "Animals & Nature": "leaf",
    "Food & Drink": "cup.and.saucer", "Travel & Places": "car", "Activities": "soccerball",
    "Objects": "lightbulb", "Symbols": "heart", "Flags": "flag",
}
def esc(s):
    return s.replace("\\", "\\\\").replace('"', '\\"')
out = ["// Generated by scripts/gen-emoji-catalog.py from Unicode's emoji-test.txt (5.12). Do not edit.",
       "", "/// The icon picker's emoji, in Unicode's groups and order, each with its name for search.",
       "enum EmojiCatalog {",
       "    struct Group: Identifiable {",
       "        let name: String",
       "        /// The SF Symbol of its button in the picker's group bar.",
       "        let symbol: String",
       "        /// Emoji and name, alternating.",
       "        let items: [String]",
       "        var id: String { name }",
       "    }", "", "    static let groups: [Group] = ["]
total = 0
for name, items in groups:
    total += len(items)
    out.append(f'        Group(name: "{esc(name)}", symbol: "{symbols.get(name, "circle")}", items: [')
    for emoji, title in items:
        out.append(f'            "{esc(emoji)}", "{esc(title)}",')
    out.append("        ]),")
out += ["    ]", "}", ""]
open("Packages/Sidebar/Sources/Sidebar/EmojiCatalog.swift", "w", encoding="utf-8").write("\n".join(out))
print(f"{len(groups)} groups, {total} emoji")
